"""Long-path handling: generated library paths must stay under MAX_PATH."""

from __future__ import annotations

import os
from pathlib import Path

import pytest

from models.paper import Paper
from services.library_service import LibraryService
from utils.config import load_settings
from utils.filename import MAX_PATH, long_path, shorten_for_windows


def _deep_root(base: Path, target_len: int = 170) -> Path:
    """Create a real nested directory close to (but under) MAX_PATH."""
    current = base
    while len(str(current)) < target_len:
        current = current / ("d" * 20)
        os.makedirs(str(current), exist_ok=True)
    return current


def _long_paper() -> Paper:
    return Paper(
        title=(
            "Convolutional Global Context and Reliability-Aware Multimodal Fusion "
            "for Optical-SAR Change Detection under Fog Cloud Degradation "
            "and Cross-Event Generalization"
        ),
        authors=["Alexandros Konstantinopoulos-Verylongsurname", "Li Wang"],
        year=2026,
        venue="IEEE TGRS",
    )


def test_generated_path_stays_under_windows_limit(tmp_path):
    deep = _deep_root(tmp_path)
    settings = load_settings(home=tmp_path)
    settings.paths.library_dir = deep / "library"
    library = LibraryService(settings)

    destination = library.destination_for(_long_paper())
    assert len(str(destination)) <= MAX_PATH + 1, len(str(destination))
    assert destination.suffix == ".pdf"
    # The library directory component is untouched.
    assert destination.parent.name == "TGRS"
    assert destination.parent.parent.name == "2026"


def test_deep_destination_can_actually_be_created(tmp_path):
    deep = _deep_root(tmp_path, target_len=190)
    settings = load_settings(home=tmp_path)
    settings.paths.library_dir = deep / "library"
    library = LibraryService(settings)

    destination = library.reserve_destination(_long_paper())
    destination.write_bytes(b"%PDF-1.4\n%%EOF\n")

    assert destination.exists()
    assert destination.stat().st_size > 0
    assert len(str(destination)) < 260


def test_shorten_for_windows_leaves_short_paths_alone(tmp_path):
    path = tmp_path / "2026" / "TGRS" / "short_name.pdf"
    assert shorten_for_windows(path) == path


def test_shorten_for_windows_truncates_long_filename(tmp_path):
    long_name = "y" * 220 + ".pdf"
    path = tmp_path / long_name
    assert len(str(path)) > MAX_PATH

    shortened = shorten_for_windows(path, max_path=MAX_PATH)

    assert len(str(shortened)) <= MAX_PATH
    assert shortened.suffix == ".pdf"
    assert shortened.parent == path.parent


def test_shorten_for_windows_never_crashes_on_huge_directories(tmp_path):
    # The directory part is generated by the app (year/venue) and is short; if
    # a caller passes an absurd directory the helper still returns a usable
    # filename instead of raising.
    path = tmp_path / ("x" * 200) / ("y" * 100 + ".pdf")
    shortened = shorten_for_windows(path, max_path=MAX_PATH)
    assert shortened.suffix == ".pdf"
    assert len(shortened.stem) >= 8


@pytest.mark.skipif(os.name != "nt", reason="Windows long-path prefix only")
def test_long_path_prefix_helper(tmp_path):
    deep = _deep_root(tmp_path, target_len=230)
    target = deep / "file.pdf"
    prefixed = long_path(target)
    assert prefixed.startswith("\\\\?\\")
    # Short paths are returned unchanged.
    assert not long_path(tmp_path / "a.pdf").startswith("\\\\?\\")
